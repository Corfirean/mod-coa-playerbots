"""Reborn class abilities up to level 60 that the stock trainer table does not teach.

The bot setup learns class abilities from the stock `trainer_spell` table. A Warcraft Reborn trainer teaches more (the
demons of a warlock, the pet spells of a hunter, the rogue poisons, Growl, the stances, ...). This lists them, from the
free-pick catalog, so the bot can learn them at the level a player would. Writes module/src/RebornExtraSpells.inc.

    python extra_spells.py
    python extra_spells.py --list     # print instead of writing
"""
import collections, os, re, struct, sys
import rsim, spelldb

OFF = 1100000
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "..", "module", "src")
SQL = os.environ.get("CORE_BASE_SQL", r"C:\games\coa-core-fork\data\sql\base\db_world")
CLS = {1: "Warrior", 2: "Paladin", 3: "Hunter", 4: "Rogue", 5: "Priest", 7: "Shaman", 8: "Mage", 9: "Warlock", 11: "Druid"}
# Spec-specific forms and totems that the bot setup hands out by itself (ApplyRebornBotSetup) or that no profile uses.
SKIP = {1154321, 1182001}
ROW_ALTERNATE = 0x80000   # an alternative form of another row: the trainer does not list it

db = spelldb.SpellDb()
types, rows, budget = rsim.load()

trainer = {}
for m in re.finditer(r"\((\d+),(\d+),(\d+),'", open(os.path.join(SQL, "trainer.sql"), encoding="utf-8").read()):
    trainer[int(m.group(1))] = (int(m.group(2)), int(m.group(3)))
taught = collections.defaultdict(set)
for m in re.finditer(r"\((\d+),(\d+),(\d+),(\d+),(\d+),(\d+),(\d+),(\d+),(\d+),(-?\d+)\)",
                     open(os.path.join(SQL, "trainer_spell.sql"), encoding="utf-8").read()):
    t = int(m.group(1))
    if t in trainer and trainer[t][0] == 0:
        taught[trainer[t][1]].add(int(m.group(2)))

b = open(os.path.join(rsim.D, "SpellRank.dbc"), "rb").read()
n, f, sz, ss = struct.unpack_from("<4I", b, 4)
chain = collections.defaultdict(dict)
for i in range(n):
    r = struct.unpack_from("<%dI" % (sz // 4), b, 20 + i * sz)
    if r[3]:
        chain[r[1]][r[3]] = r[2]
first_of = {sp: fst for fst, ranks in chain.items() for sp in ranks.values()}

out = []
for cls, name in CLS.items():
    sim = rsim.Sim(types, rows, budget, cls, 60)
    for r in sorted(rows.values(), key=lambda r: (r["level"], r["id"])):
        if (not sim.admits(r) or r["type"] != "Ability" or not (r["flags"] & rsim.ROW_DISPLAY) or r["flags"] & (rsim.ROW_DISABLED | rsim.ROW_DEPRECATED)
                or r["flags"] & (rsim.ROW_AUTOMATIC | ROW_ALTERNATE) or r["expansion"] > 0 or not r["realms"][0] or not (1 <= r["level"] <= 60)):
            continue
        s0 = r["spells"][0]
        stock = s0 - OFF if s0 > OFF else s0
        ladder = list(chain.get(first_of.get(stock, stock), {1: stock}).values())
        ladder += list(chain.get(first_of.get(s0, s0), {1: s0}).values())
        known = set()
        for sp in ladder:
            known.add(sp)
            known.add(sp + OFF if sp < OFF else sp - OFF)
        if known & taught[cls] or s0 in SKIP:
            continue
        ranks = sorted({sp for sp in chain.get(first_of.get(s0, s0), {1: s0}).values()} | {s0})
        if len(ranks) == 1:
            # Reborn-only abilities (the poisons, ...) are missing from SpellRank.dbc: their ranks are the next ids with the same name.
            probe = s0
            while True:
                probe += 1
                if db.name(probe) != db.name(s0) or not (db.s(probe, 153) or "").startswith("Rank "):
                    break
                ranks.append(probe)
        for idx, sp in enumerate(ranks):
            # never before the spell's own level: ForgetClassSpellsAbove drops class spells above the bot's level at the next level-up
            level = max(r["level"], db.u(sp, 39) or 0)
            if level > 60:
                continue
            ids = {sp}
            if sp > OFF and db.name(sp - OFF):
                ids.add(sp - OFF)        # the stock twin; a stock summon needs no reagent, its Reborn twin does
            for sid in sorted(ids):
                out.append((cls, level, sid, r["name"]))

if "--list" in sys.argv:
    for cls, level, sid, nm in out:
        print(CLS[cls], level, sid, nm)
    print(len(out), "entries")
    sys.exit(0)

lines = ["// Generated by tools/reborn_talent_planner/extra_spells.py from the Reborn catalog; do not edit by hand.",
         "// Reborn class abilities up to level 60 that the stock trainer table lacks: {class, level that teaches it, spell}.",
         "static constexpr RebornExtraSpell REBORN_EXTRA_SPELLS[] =", "{"]
cur = None
for cls, level, sid, nm in out:
    lines.append(f"    {{ {cls}, {level}, {sid} }},  // {CLS[cls]}: {nm}")
lines.append("};")
target = (sys.argv[sys.argv.index("--out") + 1] if "--out" in sys.argv else os.path.join(SRC, "RebornExtraSpells.inc"))
with open(target, "w", encoding="utf-8", newline="\n") as handle:
    handle.write("\n".join(lines) + "\n")
print("wrote", os.path.normpath(target), len(out), "entries")
