"""Plans the talent points of a hunter's pet and writes module/src/RebornPetTalents.inc.

A hunter's pet (the module gives hunters a wolf, a Ferocity family) earns one talent point at level 20 and one more every 4
levels ((level - 16) / 4: 11 at level 60). The core only teaches a talent when the points spent in its tab reach
row * 3 and its prerequisite is known (Player::LearnPetTalent), so the plan is a list of single points in an order that is
valid when followed from the start; a point the core refuses is simply skipped by the bot.

    python pet_talents.py
"""
import os, struct, sys
import rsim, spelldb

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "..", "module", "src")
TAB = 410                         # Ferocity: the wolf's family
WANTED = [("Cobra Reflexes", 2), ("Spiked Collar", 3), ("Culling the Herd", 3), ("Spider's Bite", 3), ("Great Stamina", 3),
          ("Natural Armor", 2), ("Bloodthirsty", 2), ("Heart of the Phoenix", 1)]
FILLER = ["Great Stamina", "Natural Armor", "Cobra Reflexes"]   # first-row talents that open the next row
MAX_POINTS = 16                                                   # level 80

db = spelldb.SpellDb()
t = rsim.Dbc(os.path.join(rsim.D, "Talent.dbc"))
talents = {}
for i in range(t.n):
    r = struct.unpack_from("<23I", t.rec(i))
    if r[1] != TAB:
        continue
    ranks = [x for x in r[4:9] if x]
    talents[db.name(ranks[0])] = dict(id=r[0], row=r[2], ranks=len(ranks), dep=r[13], dep_rank=r[16])
by_id = {v["id"]: v for v in talents.values()}

learned = {}
steps = []


def valid(name):
    v = talents[name]
    if learned.get(name, 0) >= v["ranks"]:
        return False
    if sum(learned.values()) < v["row"] * 3:
        return False
    if v["dep"]:
        dep = by_id[v["dep"]]
        depname = [n for n, x in talents.items() if x is dep][0]
        if learned.get(depname, 0) < v["dep_rank"] + 1:
            return False
    return True


while len(steps) < MAX_POINTS:
    pick = next((n for n, want in WANTED if learned.get(n, 0) < want and valid(n)), None)
    if pick is None:
        pick = next((n for n in FILLER if valid(n)), None)
    if pick is None:
        break
    steps.append((talents[pick]["id"], learned.get(pick, 0), pick))
    learned[pick] = learned.get(pick, 0) + 1

lines = ["// Generated by tools/reborn_talent_planner/pet_talents.py from Talent.dbc; do not edit by hand.",
         "// A hunter pet's talent points in the order to spend them: {talent id, rank index to learn}. Ferocity (the wolf's tab).",
         "static constexpr RebornPetPick REBORN_PET_PICKS[] =", "{"]
lines += [f"    {{ {tid}, {rank} }},  // {name} rank {rank + 1}" for tid, rank, name in steps]
lines.append("};")
if "--list" in sys.argv:
    print("\n".join(lines))
    sys.exit(0)
target = sys.argv[sys.argv.index("--out") + 1] if "--out" in sys.argv else os.path.join(SRC, "RebornPetTalents.inc")
with open(target, "w", encoding="utf-8", newline="\n") as handle:
    handle.write("\n".join(lines) + "\n")
print("wrote RebornPetTalents.inc,", len(steps), "points")
